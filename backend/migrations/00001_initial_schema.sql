CREATE TABLE "delivery_routes" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "reference_code" varchar(30) UNIQUE NOT NULL,
  "origin_warehouse_id" bigint NOT NULL,
  "scheduled_on" date NOT NULL,
  "status" route_status NOT NULL DEFAULT 'waiting',
  "assigned_to" bigint,
  "started_at" timestamp,
  "completed_at" timestamp,
  "created_by" bigint NOT NULL,
  "created_at" timestamp NOT NULL,
  "updated_at" timestamp NOT NULL,
  CHECK (status <> 'completed' OR (started_at IS NOT NULL AND completed_at IS NOT NULL)),
  CHECK (completed_at IS NULL OR (started_at IS NOT NULL AND completed_at >= started_at))
);

CREATE TABLE "deliveries" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "family_id" bigint,
  "partner_organization_id" bigint,
  "route_id" bigint,
  "stop_sequence" integer CHECK (stop_sequence > 0),
  "status" delivery_status NOT NULL DEFAULT 'waiting',
  "destination_address" text NOT NULL,
  "destination_latitude" decimal(9,6) CHECK (destination_latitude BETWEEN -90 AND 90),
  "destination_longitude" decimal(9,6) CHECK (destination_longitude BETWEEN -180 AND 180),
  "scheduled_at" timestamp,
  "dispatched_at" timestamp,
  "delivered_at" timestamp,
  "description" varchar(255),
  "notes" text,
  "created_by" bigint NOT NULL,
  "created_at" timestamp NOT NULL,
  "updated_at" timestamp NOT NULL,
  CHECK ((family_id IS NOT NULL AND partner_organization_id IS NULL) OR (family_id IS NULL AND partner_organization_id IS NOT NULL)),
  CHECK ((route_id IS NULL AND stop_sequence IS NULL) OR (route_id IS NOT NULL AND stop_sequence IS NOT NULL)),
  CHECK ((destination_latitude IS NULL AND destination_longitude IS NULL) OR (destination_latitude IS NOT NULL AND destination_longitude IS NOT NULL)),
  CHECK (status <> 'delivered' OR delivered_at IS NOT NULL),
  CHECK (delivered_at IS NULL OR delivered_at >= created_at),
  CHECK (dispatched_at IS NULL OR dispatched_at >= created_at),
  CHECK (delivered_at IS NULL OR dispatched_at IS NULL OR delivered_at >= dispatched_at)
);

CREATE TABLE "delivery_items" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
