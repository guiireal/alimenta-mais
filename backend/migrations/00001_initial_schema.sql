CREATE TABLE "products" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "category_id" bigint NOT NULL,
  "name" varchar(200) NOT NULL,
  "unit" varchar(20) NOT NULL,
  "is_active" boolean NOT NULL DEFAULT true,
  "created_at" timestamp NOT NULL,
  "updated_at" timestamp NOT NULL
);

CREATE TABLE "warehouses" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(100) UNIQUE NOT NULL,
  "address" text,
  "latitude" decimal(9,6) CHECK (latitude BETWEEN -90 AND 90),
  "longitude" decimal(9,6) CHECK (longitude BETWEEN -180 AND 180),
  "is_active" boolean NOT NULL DEFAULT true,
  CHECK ((latitude IS NULL AND longitude IS NULL) OR (latitude IS NOT NULL AND longitude IS NOT NULL))
);

CREATE TABLE "donations" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "donor_id" bigint NOT NULL,
  "status" donation_status NOT NULL DEFAULT 'draft',
  "received_at" timestamp,
  "document_reference" varchar(150),
  "document_path" varchar(500),
  "notes" text,
  "created_by" bigint NOT NULL,
  "confirmed_by" bigint,
  "confirmed_at" timestamp,
  "created_at" timestamp NOT NULL,
  "updated_at" timestamp NOT NULL,
  CHECK (status = 'draft' OR received_at IS NOT NULL),
  CHECK ((confirmed_at IS NULL AND confirmed_by IS NULL) OR (confirmed_at IS NOT NULL AND confirmed_by IS NOT NULL))
);

CREATE TABLE "inventory_batches" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "donation_id" bigint,
  "product_id" bigint NOT NULL,
  "batch_code" varchar(100) NOT NULL,
  "received_quantity" decimal(12,3) NOT NULL CHECK (received_quantity > 0),
  "unit_weight_kg" decimal(12,6) NOT NULL CHECK (unit_weight_kg > 0),
  "expires_on" date,
  "triage_status" triage_status NOT NULL DEFAULT 'pending',
  "triaged_by" bigint,
  "triaged_at" timestamp,
  "triage_notes" text,
  "created_at" timestamp NOT NULL,
  "updated_at" timestamp NOT NULL,
  CHECK (triage_status = 'pending' OR (triaged_by IS NOT NULL AND triaged_at IS NOT NULL))
);

CREATE TABLE "families" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "reference_code" varchar(30) UNIQUE NOT NULL,
  "contact_name" varchar(150) NOT NULL,
  "phone" varchar(30),
  "household_size" integer NOT NULL CHECK (household_size > 0),
  "address" text NOT NULL,
  "neighborhood" varchar(100) NOT NULL,
  "city" varchar(100) NOT NULL,
  "state" varchar(2) NOT NULL,
  "postal_code" varchar(8),
  "latitude" decimal(9,6) CHECK (latitude BETWEEN -90 AND 90),
  "longitude" decimal(9,6) CHECK (longitude BETWEEN -180 AND 180),
  "consent_granted_at" timestamp,
  "consent_revoked_at" timestamp,
  "privacy_notice_version" varchar(30),
  "is_active" boolean NOT NULL DEFAULT true,
  "created_at" timestamp NOT NULL,
  "updated_at" timestamp NOT NULL,
  CHECK ((latitude IS NULL AND longitude IS NULL) OR (latitude IS NOT NULL AND longitude IS NOT NULL)),
  CHECK (consent_granted_at IS NULL OR privacy_notice_version IS NOT NULL),
  CHECK (consent_revoked_at IS NULL OR (consent_granted_at IS NOT NULL AND consent_revoked_at >= consent_granted_at))
);

