CREATE TABLE "stock_movements" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "batch_id" bigint NOT NULL,
  "type" stock_movement_type NOT NULL,
  "quantity" decimal(12,3) NOT NULL CHECK (quantity > 0),
  "from_warehouse_id" bigint,
  "to_warehouse_id" bigint,
  "delivery_item_id" bigint,
  "reason" text,
  "moved_at" timestamp NOT NULL,
  "recorded_by" bigint NOT NULL,
  "created_at" timestamp NOT NULL,
  CHECK ((type IN ('receipt', 'return', 'adjustment_in') AND from_warehouse_id IS NULL AND to_warehouse_id IS NOT NULL) OR (type IN ('distribution', 'expiration_loss', 'other_loss', 'adjustment_out') AND from_warehouse_id IS NOT NULL AND to_warehouse_id IS NULL) OR (type = 'transfer' AND from_warehouse_id IS NOT NULL AND to_warehouse_id IS NOT NULL AND from_warehouse_id <> to_warehouse_id)),
  CHECK ((type IN ('distribution', 'return') AND delivery_item_id IS NOT NULL) OR (type NOT IN ('distribution', 'return') AND delivery_item_id IS NULL)),
  CHECK (type NOT IN ('expiration_loss', 'other_loss', 'adjustment_in', 'adjustment_out', 'return') OR reason IS NOT NULL)
);

